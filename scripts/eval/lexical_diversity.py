def extract_dialogues(data):
    conversations = []

    for item in data:
        convo_turns = []
        for message in item['convo']:
            if message['role'] in ['user', 'assistant']:
                convo_turns.append({
                    "role": message['role'],
                    "content": message['content'].strip()
                })
        if convo_turns:
            conversations.append(convo_turns)

    return conversations

def get_dialogue_transcript(conversation, role='user'):
    transcript = ""
    for turn in conversation:
        if role == 'both':
            transcript += f"{turn['content']} "
        elif turn['role'] == role:
            transcript += f"{turn['content']} "
    return transcript

def aggregate_transcripts(data):
    transcript = ""
    for item in data:
        transcript += item['query']
    return transcript


def compute_diversity(data: list[dict]): 
    user_tokens_ld = ld.tokenize(aggregate_transcripts(data))
    num_turns = len(data)
    user_tokens_nltk = word_tokenize(aggregate_transcripts(data))
    
    mtld_score = ld.mtld(user_tokens_ld)
    root_ttr = ld.root_ttr(user_tokens_ld)
    log_ttr = ld.log_ttr(user_tokens_ld)
    hdd = ld.hdd(user_tokens_ld)
    vocab_size = len(set(t.lower() for t in user_tokens_nltk))
    tokens_per_turn = len(user_tokens_nltk)/num_turns
    num_tokens = len(user_tokens_nltk)
    return mtld_score, root_ttr, log_ttr, hdd, vocab_size, tokens_per_turn, num_tokens


def compute_specificity_score(conversations: list[dict]):
    # refer: https://arxiv.org/pdf/1902.08654
    # compute the specificity score(NIDF) for each turn in the conversations based on the richtech data corpus
    # 1. get the richtech data corpus
    datafilepat  = '/local2/user_simulator/richtech_real_data/richtech_conv_240713_250713.json'
    if not os.path.exists(datafilepat):
        print(f"Error: {datafilepat} does not exist")
        return 0.0
    
    with open(datafilepat, 'r') as f:
        richtech_data = json.load(f)
    corpus = []
    for convo in richtech_data:
        for turn in convo['convo']:
            if turn['role'] == 'user':
                corpus.append(turn['content'])
    
    # 2. for each turn in the conversations, compute the NIDF score
    # NIDF(w) = (IDF(w) – idf_min) / (idf_max – idf_min), where idf_min and idf_max are the minimum and maximum IDF values taken over all words in the vocabulary.
    # IDF(w) = log(N_r / N_w), where N_r is the total number of responses in the corpus and N_w is the number of responses containing word w.
    nidf_scores = []
    idf_scores = []
    for convo in conversations:
        for turn in convo['convo']:
            if turn['role'] == 'user':
                turn_tokens = turn['content'].split(' ')
                for token in turn_tokens:
                    idf = np.log((len(corpus)+1) / (len([t for t in corpus if token in t])+1))
                    idf_scores.append(idf)
    idf_min = np.min(idf_scores)
    idf_max = np.max(idf_scores)
    for idf in idf_scores:
        nidf_scores.append((idf - idf_min) / (idf_max - idf_min))
    # 3. return the average NIDF score
    return float(np.mean(nidf_scores))

def compute_distinct_k_score(data: list[dict]):
    # refer: https://arxiv.org/pdf/2303.01580, https://arxiv.org/html/2412.21102v2
    from tqdm import tqdm
    """
    Produces distinct @ k for each prompt
    Modified from: https://github.com/alisawuffles/DExperts/blob/main/scripts/evaluation/evaluate_generations.py#L36-L56
    Args:
        outputs (list[dict]): list of text outputs generated by the model
    Returns:
        dict: distinct@k's
    """
    dist1, dist2, dist3 = [], [], []
    unigrams, bigrams, trigrams = [], [], []
    for item in tqdm(data, total=len(data), desc='Evaluating k-distinctness'):
        user_utterances = item['query']
        o = user_utterances.split(' ')
        unigrams.extend(o)
        for i in range(len(o) - 1):
            bigrams.append(o[i] + '_' + o[i+1])
        for i in range(len(o) - 2):
            trigrams.append(o[i] + '_' + o[i+1] + '_' + o[i+2])
    dist1 = None if len(unigrams) == 0 else len(set(unigrams)) / len(unigrams)
    dist2 = None if len(bigrams) == 0 else len(set(bigrams)) / len(bigrams)
    dist3 = None if len(trigrams) == 0 else len(set(trigrams)) / len(trigrams)

    # take the mean across prompts
    return {
        'distinct@1': round(np.nanmean(dist1), 3) if dist1 is not None else dist1,
        'distinct@2': round(np.nanmean(dist2), 3) if dist2 is not None else dist2,
        'distinct@3': round(np.nanmean(dist3), 3) if dist3 is not None else dist3
    }
    
def compute_ngram_entropy(data: list[dict]):
    # refer: https://aclanthology.org/2020.findings-emnlp.396.pdf
    from collections import Counter
    from math import log2

    user_tokens_ld = ld.tokenize(aggregate_transcripts(data))
    tokens = [t.lower() for t in user_tokens_ld if t.strip() != ""]

    def entropy_k(k: int) -> float:
        if k <= 0 or len(tokens) < k:
            return 0.0
        total_kgrams = len(tokens) - k + 1
        kgrams = (tuple(tokens[i:i+k]) for i in range(total_kgrams))
        counts = Counter(kgrams)
        total = float(total_kgrams)
        ent = 0.0
        for c in counts.values():
            p = c / total
            if p > 0.0:
                ent -= p * log2(p)
        return ent

    return entropy_k(1), entropy_k(2), entropy_k(3)


def evaluate_lexical_diversity(data):
    """Compute user-simulator related metrics.

    Aggregate-level diversity metrics are computed once, while per-conversation
    metrics are evaluated in parallel using a thread pool to speed things up.
    """

    # ---------------------------- Aggregate metrics ---------------------------
    # Diversity metrics
    mtld_score, root_ttr, log_ttr, hdd, vocab_size, tokens_per_turn, num_tokens = (
        compute_diversity(data)
    )

    # Distince@k
    distincts = compute_distinct_k_score(data)

    # n-gram entropy
    ngram_entropy = compute_ngram_entropy(data)

    diversity_metrics = {
        "mtld_score": mtld_score,
        "hdd": hdd,
        "log_ttr": log_ttr,
        "root_ttr": root_ttr,
        "vocab_size": vocab_size,
        "distincts": distincts,
        "ngram_entropy": ngram_entropy,
        "tokens_per_turn": tokens_per_turn,
        "num_tokens": num_tokens,
    }

    return diversity_metrics


    
    